import fs from 'node:fs';
import path from 'node:path';

import type { TitleOptions } from '../title';

export interface GemkitConfig extends TitleOptions {
  /** 默认语言，没有路径前缀，默认为 `en` 或者 `src/locales` 中的第一个语言 */
  defaultLanguage?: string;
}

interface PageNode {
  pattern: string;
  file: string;
  tag: string;
  /** 同名的 `*.server.ts` */
  server?: string;
}

interface LayoutNode {
  tag: string;
  file?: string;
  pages: PageNode[];
  layouts: { pattern: string; layout: LayoutNode }[];
}

const MODULE_EXT = /\.[cm]?[jt]s$/;

const isModule = (name: string) => MODULE_EXT.test(name) && !/\.d\.[cm]?ts$|\.(test|spec)\./.test(name);

const isServerModule = (name: string) => /\.server\.[cm]?[jt]s$/.test(name);

const findModule = (dir: string, name: string) =>
  fs.readdirSync(dir).find((file) => isModule(file) && file.replace(MODULE_EXT, '') === name);

const findServerModule = (file: string) => {
  const dir = path.dirname(file);
  const serverFile = findModule(dir, `${path.basename(file).replace(MODULE_EXT, '')}.server`);
  return serverFile && path.join(dir, serverFile);
};

// `[id]` -> `:id`, `[...rest]` -> `*`
function toSegment(name: string) {
  if (/^\[\.\.\..+\]$/.test(name)) return '*';
  const param = name.match(/^\[(.+)\]$/);
  return param ? `:${param[1]}` : name;
}

function toTag(type: 'page' | 'layout', relPath: string) {
  const name = relPath
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  return `gemkit-${type}-${name || 'root'}`;
}

// 静态片段优先，其次是参数，最后是 `*`
function rankPattern(pattern: string) {
  return pattern
    .split('/')
    .filter(Boolean)
    .map((seg) => (seg === '*' ? 1 : seg.startsWith(':') ? 2 : 3));
}

function comparePattern(a: string, b: string) {
  const [ra, rb] = [rankPattern(a), rankPattern(b)];
  for (let i = 0; i < Math.max(ra.length, rb.length); i++) {
    if (ra[i] !== rb[i]) return (rb[i] || 0) - (ra[i] || 0);
  }
  return 0;
}

function scanDir(pagesDir: string, dir: string, segments: string[], layout: LayoutNode, tags: Map<string, string>) {
  const addTag = (tag: string, file: string) => {
    if (tags.has(tag)) throw new Error(`gemkit: \`${file}\` and \`${tags.get(tag)}\` have the same tag \`${tag}\``);
    tags.set(tag, file);
    return tag;
  };
  const entries = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    // `_` 开头的是特殊文件或者非页面模块
    if (/^[._]/.test(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);
    const relPath = path.relative(pagesDir, fullPath);
    if (entry.isDirectory()) {
      const subSegments = [...segments, toSegment(entry.name)];
      const layoutFile = findModule(fullPath, '_layout');
      if (!layoutFile) {
        scanDir(pagesDir, fullPath, subSegments, layout, tags);
        continue;
      }
      const file = path.join(fullPath, layoutFile);
      const subLayout: LayoutNode = { tag: addTag(toTag('layout', relPath), file), file, pages: [], layouts: [] };
      layout.layouts.push({ pattern: `/${[...subSegments, '*'].join('/')}`, layout: subLayout });
      scanDir(pagesDir, fullPath, subSegments, subLayout, tags);
    } else if (isModule(entry.name) && !isServerModule(entry.name)) {
      const name = entry.name.replace(MODULE_EXT, '');
      const pageSegments = name === 'index' ? segments : [...segments, toSegment(name)];
      layout.pages.push({
        pattern: `/${pageSegments.join('/')}`,
        file: fullPath,
        tag: addTag(toTag('page', relPath.replace(MODULE_EXT, '')), fullPath),
        server: findServerModule(fullPath),
      });
    }
  }
}

export function scanPages(pagesDir: string) {
  const tags = new Map<string, string>();
  const rootLayout = findModule(pagesDir, '_layout');
  const notFound = findModule(pagesDir, '_404');
  const root: LayoutNode = {
    tag: rootLayout ? toTag('layout', '') : '',
    file: rootLayout && path.join(pagesDir, rootLayout),
    pages: [],
    layouts: [],
  };
  scanDir(pagesDir, pagesDir, [], root, tags);
  const notFoundFile = notFound && path.join(pagesDir, notFound);
  return {
    root,
    notFound: notFoundFile && {
      pattern: '*',
      file: notFoundFile,
      tag: toTag('page', '404'),
      server: findServerModule(notFoundFile),
    },
  };
}

function writeIfChanged(file: string, content: string) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return;
  fs.writeFileSync(file, content);
}

const HEADER = '// Generated by gemkit, do not edit\n';

const toImportPath = (genDir: string, file: string) =>
  JSON.stringify(path.relative(genDir, file).replace(MODULE_EXT, ''));

/** 生成路由，返回按匹配优先级排序的页面列表 */
function generateRoutes(genDir: string, pagesDir: string) {
  const { root, notFound } = scanPages(pagesDir);
  const importPath = (file: string) => toImportPath(genDir, file);
  const element = (tag: string, props = '') => `html\`<${tag}${props}></${tag}>\``;

  // 客户端产物不能引用 `*.server.ts`
  const pageRoute = ({ pattern, file, tag, server }: PageNode) => `{
    pattern: ${JSON.stringify(pattern)},
    getContent: async (params) => {
      const data = await loadPage(() => import(${importPath(file)}), '${tag}', params${server ? ', true' : ''});
      return ${element(tag, ' .params=${params} .data=${data}')};
    },
  }`;

  const layoutRoute = (pattern: string, { file, tag }: LayoutNode) => `{
    pattern: ${JSON.stringify(pattern)},
    getContent: async () => {
      await loadLayout(() => import(${importPath(file!)}), '${tag}');
      return ${element(tag)};
    },
  }`;

  const pages: PageNode[] = [];
  const outlets: string[] = [];
  const collect = (layout: LayoutNode) => {
    pages.push(...layout.pages);
    const routes = [
      ...layout.pages.map((page) => ({ pattern: page.pattern, code: pageRoute(page) })),
      ...layout.layouts.map(({ pattern, layout: sub }) => ({ pattern, code: layoutRoute(pattern, sub) })),
    ].sort((a, b) => comparePattern(a.pattern, b.pattern));
    if (notFound) routes.push({ pattern: '*', code: 'notFound' });
    outlets.push(`  '${layout.tag}': [${routes.map(({ code }) => code).join(', ')}],`);
    layout.layouts.forEach(({ layout: sub }) => collect(sub));
  };
  collect(root);

  const code = [
    HEADER,
    `import { html } from '@mantou/gem';`,
    `import { defineElement, loadLayout, loadPage, setOutlets } from '@mantou/gemkit';`,
    root.file && `import RootLayout from ${importPath(root.file)};`,
    '',
    notFound && `const notFound = ${pageRoute(notFound)};\n`,
    `setOutlets({\n${outlets.join('\n')}\n});`,
    '',
    // 定义时会升级服务端渲染的元素，所以要在设置路由之后
    root.file ? `defineElement('${root.tag}', RootLayout);` : '',
    `export const app = ${root.file ? element(root.tag) : element('gemkit-outlet')};`,
    '',
  ];
  writeIfChanged(path.join(genDir, 'routes.ts'), code.filter((line) => line !== undefined).join('\n'));
  return { pages: pages.sort((a, b) => comparePattern(a.pattern, b.pattern)), notFound };
}

function generateI18n(genDir: string, localesDir: string, config: GemkitConfig) {
  const languages = fs.existsSync(localesDir)
    ? fs
        .readdirSync(localesDir)
        .filter((file) => file.endsWith('.json'))
        .map((file) => file.replace(/\.json$/, ''))
        .sort()
    : [];
  if (!languages.length) {
    writeIfChanged(
      path.join(genDir, 'i18n.ts'),
      `${HEADER}\nexport const i18n = undefined;\nexport const languages: string[] = [];\nexport const defaultLanguage = '';\n`,
    );
    return;
  }
  const defaultLanguage = config.defaultLanguage || (languages.includes('en') ? 'en' : languages[0]);
  if (!languages.includes(defaultLanguage))
    throw new Error(`gemkit: not found \`src/locales/${defaultLanguage}.json\``);
  const id = (lang: string) => `lang_${lang.replace(/\W/g, '_')}`;
  const code = [
    HEADER,
    `import { history } from '@mantou/gem';`,
    `import { I18n } from '@mantou/gem/helper/i18n';`,
    `import { getBasePath, localizePath as localize, splitLanguage } from '@mantou/gemkit';`,
    ...languages.map(
      (lang) =>
        `import ${id(lang)} from ${JSON.stringify(path.relative(genDir, path.join(localesDir, `${lang}.json`)))};`,
    ),
    '',
    `export const languages = ${JSON.stringify(languages)};`,
    `export const defaultLanguage = '${defaultLanguage}';`,
    '',
    `const { lang } = splitLanguage(location.pathname, languages, defaultLanguage);`,
    `history.basePath = getBasePath(lang, defaultLanguage);`,
    '',
    `export const i18n = new I18n<typeof ${id(defaultLanguage)}>({`,
    `  resources: { ${languages.map((lang) => `${JSON.stringify(lang)}: ${id(lang)}`).join(', ')} },`,
    `  fallbackLanguage: defaultLanguage,`,
    `  currentLanguage: lang,`,
    `});`,
    '',
    `/** 切换语言的路径，需要使用 \`<a>\` 跳转使页面重新加载 */`,
    `export const localizePath = (lang: string, path = history.getParams().path) => localize(lang, path, defaultLanguage);`,
    '',
  ];
  writeIfChanged(path.join(genDir, 'i18n.ts'), code.join('\n'));
}

function generateEntries(
  genDir: string,
  srcDir: string,
  config: GemkitConfig,
  { pages, notFound }: ReturnType<typeof generateRoutes>,
) {
  const importPath = (file: string) => toImportPath(genDir, file);
  const serverModules = [...pages, ...(notFound ? [notFound] : [])].filter((page) => page.server);
  const appFile = findModule(srcDir, 'app');
  const appImport = appFile
    ? `import ${JSON.stringify(path.relative(genDir, path.join(srcDir, appFile)).replace(MODULE_EXT, ''))};`
    : '';
  const titleOptions = JSON.stringify({ title: config.title, titleTemplate: config.titleTemplate });
  writeIfChanged(
    path.join(genDir, 'client.ts'),
    [
      HEADER,
      `import { startClient } from '@mantou/gemkit/client';`,
      `import './i18n';`,
      appImport,
      `import './routes';`,
      '',
      `startClient(${titleOptions});`,
      '',
    ].join('\n'),
  );
  writeIfChanged(
    path.join(genDir, 'server.ts'),
    [
      HEADER,
      `import { createRenderer } from '@mantou/gemkit/server';`,
      `import { defaultLanguage, i18n, languages } from './i18n';`,
      appImport,
      `import { app } from './routes';`,
      '',
      `const pages = [`,
      ...pages.map(
        ({ pattern, tag, file }) =>
          `  { pattern: ${JSON.stringify(pattern)}, tag: '${tag}', load: () => import(${importPath(file)}) },`,
      ),
      `];`,
      '',
      `const serverModules = {`,
      ...serverModules.map(({ tag, server }) => `  '${tag}': () => import(${importPath(server!)}),`),
      `};`,
      '',
      `export default createRenderer({`,
      `  app,`,
      `  pages,`,
      `  serverModules,`,
      `  i18n,`,
      `  languages,`,
      `  defaultLanguage,`,
      `  ...${titleOptions},`,
      `});`,
      '',
    ].join('\n'),
  );
  writeIfChanged(
    path.join(genDir, 'tsconfig.json'),
    // 通过 `files` 包含声明文件，不依赖项目的 `include`（`.` 开头的目录不会被通配符匹配）
    // `auto-import.d.ts` 由 unplugin-gem 生成
    `${JSON.stringify(
      { compilerOptions: { paths: { '$gemkit/*': ['./*'] } }, files: ['./env.d.ts', './auto-import.d.ts'] },
      null,
      2,
    )}\n`,
  );
  // CSS 等资源模块的类型声明，项目不需要自己引用
  writeIfChanged(path.join(genDir, 'env.d.ts'), `${HEADER}/// <reference types="@rsbuild/core/types" />\n`);
}

/** 生成路由、i18n 和入口文件到 `.gemkit` 目录 */
export function generate(rootPath: string, config: GemkitConfig) {
  const srcDir = path.join(rootPath, 'src');
  const genDir = path.join(rootPath, '.gemkit');
  fs.mkdirSync(genDir, { recursive: true });
  const routes = generateRoutes(genDir, path.join(srcDir, 'pages'));
  generateI18n(genDir, path.join(srcDir, 'locales'), config);
  generateEntries(genDir, srcDir, config, routes);
}
